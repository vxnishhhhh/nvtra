const assert=require('node:assert/strict');
const {readFileSync,readdirSync}=require('node:fs');
const {spawnSync}=require('node:child_process');
const {resolve}=require('node:path');
const root=resolve(__dirname,'..');
const configuration=JSON.parse(readFileSync(resolve(root,'vercel.json'),'utf8'));
assert.equal(configuration.framework,null);
assert.equal(configuration.buildCommand,'node scripts/build_vercel.cjs');
assert.equal(configuration.outputDirectory,'dist-vercel');
const build=spawnSync(process.execPath,['scripts/build_vercel.cjs'],{cwd:root,encoding:'utf8'});
assert.equal(build.status,0,build.stderr);
const output=resolve(root,configuration.outputDirectory);
assert.deepEqual(readdirSync(output).sort(),['index.html','nvtra.html','preview.html','robots.txt']);
const html=readFileSync(resolve(output,'index.html'),'utf8');
assert(html.includes('window.NVTRA_PREVIEW_CONFIG='));
assert.equal(html,readFileSync(resolve(root,'preview.html'),'utf8'));
assert.equal(html,readFileSync(resolve(output,'nvtra.html'),'utf8'));
console.log('PASS: Vercel output contains only the standalone frontend; production entry points use its no-backend mode.');
const browser=spawnSync(process.execPath,['tests/preview.cjs'],{cwd:root,env:{...process.env,NVTRA_PREVIEW_FILE:resolve(output,'index.html')},stdio:'inherit'});
process.exit(browser.status??1);
